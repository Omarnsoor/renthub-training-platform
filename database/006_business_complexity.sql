CREATE SEQUENCE RH_NOTIFICATION_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_AUDIT_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_PAYOUT_SEQ START WITH 1 INCREMENT BY 1;

