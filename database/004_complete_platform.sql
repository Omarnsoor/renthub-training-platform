CREATE SEQUENCE RH_AUTH_SESSION_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_FAVORITE_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_REVIEW_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_PAYMENT_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE RH_BOOKING_SERVICE_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE RH_AUTH_SESSIONS (
  ID NUMBER PRIMARY KEY, TOKEN VARCHAR2(100) NOT NULL UNIQUE, USER_ID NUMBER NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL, CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RH_AUTH_USER FOREIGN KEY (USER_ID) REFERENCES RH_USERS(ID)
);
CREATE TABLE RH_FAVORITES (
  ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, ASSET_TYPE VARCHAR2(20) NOT NULL, ASSET_ID NUMBER NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RH_FAV_USER FOREIGN KEY (USER_ID) REFERENCES RH_USERS(ID),
  CONSTRAINT UQ_RH_FAVORITE UNIQUE (USER_ID,ASSET_TYPE,ASSET_ID)
);
CREATE TABLE RH_REVIEWS (
  ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, ASSET_TYPE VARCHAR2(20) NOT NULL, ASSET_ID NUMBER NOT NULL,
  RATING NUMBER(1) NOT NULL, COMMENT VARCHAR2(1000), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RH_REVIEW_USER FOREIGN KEY (USER_ID) REFERENCES RH_USERS(ID),
  CONSTRAINT CK_RH_REVIEW_RATING CHECK (RATING BETWEEN 1 AND 5),
  CONSTRAINT UQ_RH_REVIEW UNIQUE (USER_ID,ASSET_TYPE,ASSET_ID)
);
CREATE TABLE RH_PAYMENTS (
  ID NUMBER PRIMARY KEY, BOOKING_ID NUMBER NOT NULL UNIQUE, USER_ID NUMBER NOT NULL, AMOUNT NUMBER(12,2) NOT NULL,
  METHOD VARCHAR2(30) NOT NULL, STATUS VARCHAR2(30) DEFAULT 'PAID' NOT NULL,
  REFERENCE_NO VARCHAR2(80) NOT NULL UNIQUE, CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RH_PAYMENT_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES RH_BOOKINGS(ID),
  CONSTRAINT FK_RH_PAYMENT_USER FOREIGN KEY (USER_ID) REFERENCES RH_USERS(ID)
);
CREATE TABLE RH_BOOKING_SERVICES (
  ID NUMBER PRIMARY KEY, BOOKING_ID NUMBER NOT NULL, SERVICE_ID NUMBER NOT NULL, PRICE NUMBER(12,2) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_RH_BS_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES RH_BOOKINGS(ID),
  CONSTRAINT FK_RH_BS_SERVICE FOREIGN KEY (SERVICE_ID) REFERENCES RH_EXTRA_SERVICES(ID),
  CONSTRAINT UQ_RH_BOOKING_SERVICE UNIQUE (BOOKING_ID,SERVICE_ID)
);

